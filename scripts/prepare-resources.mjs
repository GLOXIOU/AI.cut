// Copies bundled fonts (latin + latin-ext) and vendor scripts into resources/.
// Run automatically before builds (npm run prepare-resources).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BUNDLED_FONTS } from '../shared/fonts.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nm = path.join(root, 'node_modules');
const fontsOut = path.join(root, 'resources', 'fonts');
const vendorOut = path.join(root, 'resources', 'vendor');
fs.mkdirSync(fontsOut, { recursive: true });
fs.mkdirSync(vendorOut, { recursive: true });

let css = '/* Generated by scripts/prepare-resources.mjs — bundled OFL fonts */\n';
let copied = 0;
for (const f of BUNDLED_FONTS) {
  const pkgDir = path.join(nm, '@fontsource', f.pkg);
  if (!fs.existsSync(pkgDir)) { console.warn('missing font package', f.pkg); continue; }
  for (const w of f.weights) {
    const cssFile = path.join(pkgDir, `${w}.css`);
    if (!fs.existsSync(cssFile)) { console.warn('missing weight', f.pkg, w); continue; }
    const src = fs.readFileSync(cssFile, 'utf8');
    const blocks = src.match(/\/\*[^*]*\*\/\s*@font-face\s*{[^}]+}/g) || [];
    for (const b of blocks) {
      const subset = (b.match(/\/\*\s*([\w-]+)\s*\*\//) || [])[1] || '';
      if (!/-(latin|latin-ext)-\d+-normal$/.test(subset)) continue;
      const file = (b.match(/url\(\.\/files\/([^)]+\.woff2)\)/) || [])[1];
      const range = (b.match(/unicode-range:\s*([^;]+);/) || [])[1];
      if (!file) continue;
      fs.copyFileSync(path.join(pkgDir, 'files', file), path.join(fontsOut, file));
      copied++;
      css += `@font-face{font-family:'${f.family}';font-style:normal;font-display:block;font-weight:${w};` +
        `src:url('./${file}') format('woff2');${range ? `unicode-range:${range};` : ''}}\n`;
    }
  }
}
fs.writeFileSync(path.join(fontsOut, 'fonts.css'), css);
console.log(`fonts: ${copied} files copied`);

fs.mkdirSync(path.join(vendorOut, 'ort'), { recursive: true });
for (const [from, to] of [
  ['lottie-web/build/player/lottie.min.js', 'lottie.min.js'],
  // ONNX Runtime Web (WebGPU + wasm) for the subject cutout (electron/segment)
  ['onnxruntime-web/dist/ort.webgpu.bundle.min.mjs', 'ort/ort.webgpu.bundle.min.mjs'],
  ['onnxruntime-web/dist/ort-wasm-simd-threaded.asyncify.wasm', 'ort/ort-wasm-simd-threaded.asyncify.wasm'],
  ['onnxruntime-web/dist/ort-wasm-simd-threaded.asyncify.mjs', 'ort/ort-wasm-simd-threaded.asyncify.mjs'],
]) {
  if (!fs.existsSync(path.join(nm, from))) { console.warn('missing vendor file', from); continue; }
  fs.copyFileSync(path.join(nm, from), path.join(vendorOut, to));
}
console.log('vendor scripts copied');
