export function t(key, vars) {
  const lang = useStore.getState().lang === 'en' ? 1 : 0;
  let s = D[key] ? D[key][lang] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

/** Hook re-rendering on language change. */
export function useT() {
  useStore((s) => s.lang);
  return t;
}

/** Interface language: the user's choice, else the system's (English when the OS is not French). The AI is not affected. */
export function resolveLang(settings, info) {
  const l = settings?.language;
  if (l === 'fr' || l === 'en') return l;
  return info?.systemLanguage || useStore.getState().lang;
}

/** Current interface language ('fr' | 'en'), re-rendering on change. */
export function useLang() {
  return useStore((s) => s.lang);
}

/** Quote a title the way the interface language does it. */
export const quote = (s) => (useStore.getState().lang === 'en' ? `“${s}”` : `« ${s} »`);

/** Job status word (queued / running / done / error / canceled). */
export const jobStatus = (s) => (D[`status_${s}`] ? t(`status_${s}`) : s);

/** Display name of a motion template (built-in names are authored in French). */
export function tplName(tpl, lang) {
  if (!tpl) return '';
  return lang === 'en' && !tpl.user ? TEMPLATE_NAMES_EN[tpl.id] || tpl.name : tpl.name;
}

/** Display label of a motion template setting. */
export const paramLabel = (label, lang) => (lang === 'en' ? PARAM_LABELS_EN[label] || label : label);

/** Display name + hint of a caption style preset. */
export function presetText(id, p, lang) {
  if (lang !== 'en') return { label: p.label, hint: p.hint || '' };
  const en = SUBTITLE_PRESETS_EN[id];
  if (Array.isArray(en)) return { label: en[0], hint: en[1] };
  return { label: en || p.labelEn || p.label, hint: '' };
}
