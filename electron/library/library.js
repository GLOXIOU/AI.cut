// ------------------------------------------------------------------ built-in (synth + real pack recordings)
function builtinPath(id) { return path.join(libraryDir(), 'builtin', `${id}.wav`); }
/** File of a built-in sound: the real recording when the pack replaces it, else the synthesized WAV. */
export function ensureBuiltin(id) {
  const real = packReplacement(id);
  if (real) return real;
  const p = builtinPath(id);
  if (!exists(p)) {
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, renderSfx(id).wav);
  }
  return p;
}
/** File of any local sound effect id ("builtin:x", "pack:x" or a bare id of either kind). */
export function sfxFile(id) {
  const bare = String(id).replace(/^(builtin|pack):/, '');
  if (!String(id).startsWith('pack:') && SFX.some((s) => s.id === bare)) return ensureBuiltin(bare);
  const p = packSfx().find((s) => s.id === bare);
  if (p) return packPath(p.file);
  throw new Error(`Unknown sound effect ${id}`);
}

export function builtinItems() {
  const pack = packSfx();
  const synth = SFX.map((s) => {
    const real = pack.find((x) => x.replaces === s.id);
    return {
      id: `builtin:${s.id}`, source: real ? 'pack' : 'builtin', kind: 'sfx', title: real ? real.fr : s.name, titleEn: real?.en || SYNTH_EN[s.id] || s.name,
      category: real && SFX_CATEGORIES.some(([c]) => c === real.cat) ? real.cat : s.cat, tags: [...new Set([...s.tags, ...(real?.tags || [])])],
      real: !!real, license: real ? real.license : 'CC0 (generated by AI.cut)', attributionRequired: false,
      author: real ? real.author : 'AI.cut synthesizer', duration: real?.duration ?? null, ...(real ? { landing: real.landing } : {}),
    };
  });
  const extra = pack.filter((x) => !x.replaces).map((x) => ({
    id: `pack:${x.id}`, source: 'pack', kind: 'sfx', title: x.fr, titleEn: x.en, category: x.cat, tags: x.tags, real: true,
    license: x.license, attributionRequired: false, author: x.author, duration: x.duration, landing: x.landing,
  }));
  return [...synth, ...extra];
}

export function packMusicItems() {
  return packMusic().map((m) => ({
    id: `music:${m.id}`, source: 'pack', kind: 'music', title: m.title, author: m.author, duration: m.duration, category: m.cat,
    tags: m.tags || [], license: 'CC0', licenseUrl: m.licenseUrl, attributionRequired: false, local: true, landing: m.landing,
  }));
}

// ------------------------------------------------------------------ FreePD (CC0) online catalog — archive.org mirror
const FREEPD_DENY = /cornfield chase|putin|ussr|anthem|hymne|bbc/i;
const FREEPD_TAGS = Object.fromEntries(MUSIC_CATEGORIES.map(([id, fr, en]) => [id, [fr, en]]));
let freepd = null;
async function freepdCatalog() {
  if (freepd) return freepd;
  const file = path.join(libraryDir(), 'freepd.json');
  const cached = readJson(file);
  if (cached && Date.now() - cached.at < 30 * 86400e3) { freepd = cached.items; return freepd; }
  try {
    const meta = await fetchJson('https://archive.org/metadata/freepd', { timeoutMs: 45000 });
    freepd = (meta.files || [])
      .filter((f) => /\.mp3$/i.test(f.name) && f.name.includes('/') && !FREEPD_DENY.test(f.name))
      .map((f) => ({ path: f.name, cat: f.name.split('/')[0], title: f.name.split('/').pop().replace(/\.mp3$/i, ''), duration: Math.round(Number(f.length)) || null }));
    writeJson(file, { at: Date.now(), items: freepd }, false);
  } catch (e) {
    log.warn('freepd catalog failed', e.message);
    freepd = cached?.items || [];
    if (!freepd.length) throw new Error(`FreePD indisponible (${e.message})`);
  }
  return freepd;
}
function freepdItem(x) {
  const url = `https://archive.org/download/freepd/${x.path.split('/').map(encodeURIComponent).join('/')}`;
  return {
    id: `freepd:${x.path}`, source: 'freepd', kind: 'music', title: x.title, author: 'FreePD.com', duration: x.duration, category: x.cat,
    tags: FREEPD_TAGS[x.cat] || [], license: 'CC0', licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/', attributionRequired: false,
    previewUrl: url, url, landing: 'https://archive.org/details/freepd',
  };
}

// ------------------------------------------------------------------ Incompetech
let incompetech = null;
async function incompetechCatalog() {
  if (incompetech) return incompetech;
  const file = path.join(libraryDir(), 'incompetech.json');
  const cached = readJson(file);
  if (cached && Date.now() - cached.at < 7 * 86400e3) { incompetech = cached.items; return incompetech; }
  try {
    const list = await fetchJson('https://incompetech.com/music/royalty-free/pieces.json', { timeoutMs: 30000 });
    incompetech = list.map((x) => ({
      file: x.filename, title: x.title, feel: x.feel || '', instruments: x.instruments || '', description: x.description || '',
      bpm: Number(x.bpm) || null, duration: hms(x.length),
    }));
    writeJson(file, { at: Date.now(), items: incompetech }, false);
  } catch (e) {
    log.warn('incompetech catalog failed', e.message);
    incompetech = cached?.items || [];
  }
  return incompetech;
}
function hms(s) {
  const p = String(s || '0').split(':').map(Number);
  return p.reduce((a, v) => a * 60 + (v || 0), 0);
}
function incompetechItem(x) {
  const url = `https://incompetech.com/music/royalty-free/mp3-royaltyfree/${encodeURIComponent(x.file)}`;
  return {
    id: `incompetech:${x.file}`, source: 'incompetech', kind: 'music', title: x.title, author: 'Kevin MacLeod',
    duration: x.duration, bpm: x.bpm, tags: x.feel.split(',').map((t) => t.trim()).filter(Boolean), instruments: x.instruments,
    description: x.description, license: 'CC BY 4.0', licenseUrl: 'https://creativecommons.org/licenses/by/4.0/', attributionRequired: true,
    attribution: `"${x.title}" Kevin MacLeod (incompetech.com)\nLicensed under Creative Commons: By Attribution 4.0 License\nhttp://creativecommons.org/licenses/by/4.0/`,
    previewUrl: url, url,
  };
}

// ------------------------------------------------------------------ Openverse
// Anonymous API limits: page_size ≤ 20, 20 requests/min, 200/day → results are cached.
const ovCache = new Map(); // url -> { at, items }
async function openverseSearch({ query, kind, license, limit, page }) {
  const params = new URLSearchParams({ q: query || (kind === 'music' ? 'music' : 'sound'), page_size: String(Math.max(1, Math.min(20, limit))), page: String(page || 1), mature: 'false' });
  // default: no attribution (CC0 / public domain). "attribution-ok" also allows CC BY (no ShareAlike / NonCommercial)
  params.set('license', license === 'attribution-ok' ? 'cc0,pdm,by' : 'cc0,pdm');
  if (kind === 'music') params.set('category', 'music');
  // Freesound items carry no category on Openverse: filter SFX by provider instead
  if (kind === 'sfx') params.set('source', 'freesound');
  const url = `https://api.openverse.org/v1/audio/?${params}`;
  const hit = ovCache.get(url);
  if (hit && Date.now() - hit.at < 3600e3) return hit.items;
  let data;
  try { data = await fetchJson(url, { timeoutMs: 25000 }); } catch (e) {
    if (/HTTP 429/.test(e.message)) throw new Error(tr('limite Openverse atteinte (20 recherches/min, 200/jour sans compte) — réessaie plus tard', 'Openverse limit reached (20 searches/min, 200/day without an account) — try again later'));
    if (/HTTP 401/.test(e.message)) throw new Error(tr('Openverse a refusé la requête (401)', 'Openverse rejected the request (401)'));
    throw e;
  }
  const items = (data.results || []).map((r) => ({
    id: `openverse:${r.id}`, source: `openverse/${r.source || r.provider}`, kind: kind === 'any' ? (r.category === 'music' ? 'music' : 'sfx') : kind,
    title: r.title, author: r.creator || null, duration: r.duration ? r.duration / 1000 : null,
    license: `${String(r.license).toUpperCase()}${r.license_version ? ' ' + r.license_version : ''}`, licenseUrl: r.license_url,
    attributionRequired: !['cc0', 'pdm'].includes(r.license), attribution: r.attribution || null,
    tags: (r.tags || []).map((t) => t.name).slice(0, 10), genres: r.genres || [], filetype: r.filetype,
    previewUrl: r.url, url: r.url, landing: r.foreign_landing_url,
  }));
  ovCache.set(url, { at: Date.now(), items });
  if (ovCache.size > 200) ovCache.delete(ovCache.keys().next().value);
  return items;
}

// ------------------------------------------------------------------ unified search
const norm = (s) => String(s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');

/**
 * Search the free library. opts: { query, kind: 'music'|'sfx'|'any', source: 'all'|'builtin'|'pack'|'freepd'|'openverse'|'incompetech',
 *   license: 'no-attribution'|'attribution-ok', limit, page, minDuration, maxDuration, bpmMin, bpmMax, category }
 */
export async function searchLibrary(opts = {}) {
  const { query = '', kind = 'any', source = 'all', license = 'attribution-ok', limit = 20, page = 1 } = opts;
  const q = norm(query).trim();
  const words = q.split(/\s+/).filter(Boolean);
  const out = [];
  const errors = [];
  const match = (text) => !words.length || words.every((w) => text.includes(w));
  const durOk = (d) => (!opts.minDuration || !d || d >= opts.minDuration) && (!opts.maxDuration || !d || d <= opts.maxDuration);
  const local = source === 'all' || source === 'builtin' || source === 'pack';
  if (local && kind !== 'music') {
    const hits = [];
    for (const it of builtinItems()) {
      if (opts.category && it.category !== opts.category) continue;
      const text = norm(`${it.title} ${it.titleEn || ''} ${it.category} ${it.tags.join(' ')}`);
      const full = match(text);
      if (full || (words.length && words.some((w) => text.includes(w)))) hits.push({ ...it, score: (full ? 2 : 1) + (it.real ? 0.5 : 0) });
    }
    hits.sort((a, b) => b.score - a.score);
    out.push(...hits);
  }
  if (local && kind !== 'sfx') {
    const hits = packMusicItems().filter((x) => (!opts.category || x.category === opts.category) && durOk(x.duration) && match(norm(`${x.title} ${x.category} ${x.tags.join(' ')}`)));
    out.push(...hits);
  }
  if ((source === 'all' || source === 'freepd') && kind !== 'sfx') {
    try {
      const cat = await freepdCatalog();
      const have = new Set(packMusicItems().map((x) => norm(x.title)));
      let list = cat.filter((x) => !have.has(norm(x.title)) && (!opts.category || x.cat === opts.category) && durOk(x.duration))
        .filter((x) => match(norm(`${x.title} ${x.cat} ${(FREEPD_TAGS[x.cat] || []).join(' ')}`)));
      // named categories first, the long "Page2"/"misc" tail after
      list = [...list.filter((x) => x.cat !== 'Page2' && x.cat !== 'misc'), ...list.filter((x) => x.cat === 'Page2' || x.cat === 'misc')];
      const start = (page - 1) * limit;
      out.push(...list.slice(start, start + limit).map(freepdItem));
    } catch (e) { errors.push(`FreePD: ${e.message}`); }
  }
  if ((source === 'all' || source === 'incompetech') && kind !== 'sfx' && license === 'attribution-ok') {
    try {
      const cat = await incompetechCatalog();
      let list = cat.filter((x) => match(norm(`${x.title} ${x.feel} ${x.instruments} ${x.description}`)));
      if (opts.bpmMin) list = list.filter((x) => (x.bpm || 0) >= opts.bpmMin);
      if (opts.bpmMax) list = list.filter((x) => (x.bpm || 999) <= opts.bpmMax);
      list = list.filter((x) => durOk(x.duration));
      const start = (page - 1) * limit;
      out.push(...list.slice(start, start + limit).map(incompetechItem));
    } catch (e) { errors.push(`incompetech: ${e.message}`); }
  }
  // Openverse: explicit online source, or "all" with a query (saves the anonymous daily quota)
  if (source === 'openverse' || (source === 'all' && words.length && (kind !== 'music' || license === 'attribution-ok'))) {
    try {
      const list = (await openverseSearch({ query, kind, license, limit, page })).filter((x) => durOk(x.duration));
      out.push(...list);
    } catch (e) { errors.push(`Openverse : ${e.message}`); }
  }
  for (const it of out) resultsCache.set(it.id, it);
  return { results: out.slice(0, Math.max(limit, 60)), errors };
}

/** Local preview file/URL for the UI. */
export function previewSource(id) {
  if (id.startsWith('myinstants:')) return { url: `https://www.myinstants.com/media/sounds/${id.slice(11)}` };
  if (id.startsWith('builtin:') || id.startsWith('pack:')) return { file: sfxFile(id) };
  if (id.startsWith('music:')) { const m = packMusic().find((x) => `music:${x.id}` === id); return m ? { file: packPath(m.file) } : null; }
  if (id.startsWith('freepd:')) return { url: freepdItem({ path: id.slice(7), cat: '', title: '' }).url };
  const it = resultsCache.get(id);
  return it ? { url: it.previewUrl } : null;
}

async function resolveItem(id) {
  if (resultsCache.has(id)) return resultsCache.get(id);
  if (id.startsWith('myinstants:')) { const it = await memeItem(id); return { ...it, kind: 'sfx', license: 'Mème (droits non vérifiés)', attributionRequired: false }; }
  if (id.startsWith('builtin:') || id.startsWith('pack:')) {
    const it = builtinItems().find((x) => x.id === id || x.id === `builtin:${id.slice(5)}`);
    if (it) return it;
  }
  if (id.startsWith('music:')) { const it = packMusicItems().find((x) => x.id === id); if (it) return it; }
  if (id.startsWith('freepd:')) {
    const cat = await freepdCatalog().catch(() => []);
    const x = cat.find((c) => c.path === id.slice(7)) || { path: id.slice(7), cat: id.slice(7).split('/')[0], title: id.slice(7).split('/').pop().replace(/\.mp3$/i, '') };
    return freepdItem(x);
  }
  if (id.startsWith('incompetech:')) {
    const cat = await incompetechCatalog();
    const x = cat.find((c) => c.file === id.slice(12));
    if (x) return incompetechItem(x);
  }
  if (id.startsWith('openverse:')) {
    const r = await fetchJson(`https://api.openverse.org/v1/audio/${id.slice(10)}/`);
    return {
      id, source: `openverse/${r.source}`, kind: r.category === 'music' ? 'music' : 'sfx', title: r.title, author: r.creator,
      duration: r.duration ? r.duration / 1000 : null, license: `${String(r.license).toUpperCase()} ${r.license_version || ''}`.trim(),
      licenseUrl: r.license_url, attributionRequired: !['cc0', 'pdm'].includes(r.license), attribution: r.attribution, url: r.url,
    };
  }
  throw new Error(`Unknown library item ${id} (search first)`);
}

/** Download / copy an item into the project media folder. Returns {file, item, sourceInfo}. */
export async function downloadLibraryItem(id, { signal, onProgress } = {}) {
  store.requireOpen();
  const item = await resolveItem(id);
  if (!item) throw new Error(`Unknown library item ${id}`);
  const dir = path.join(store.dir, 'media', item.kind === 'music' ? 'music' : 'sfx');
  fs.mkdirSync(dir, { recursive: true });
  let file;
  if (id.startsWith('myinstants:')) {
    const { file: cached, item: mi } = await memeFile(id, { signal });
    file = path.join(dir, `${safeFileName(mi.title, 60) || 'meme'}${path.extname(cached) || '.mp3'}`);
    // same name but another sound → new file; same sound → reuse the media already in the project
    if (exists(file) && fs.statSync(file).size !== fs.statSync(cached).size) file = uniquePath(file);
    if (!exists(file)) fs.copyFileSync(cached, file);
    return {
      file, item: mi,
      sourceInfo: { kind: 'meme', provider: 'myinstants', title: mi.title, license: 'Mème (droits non vérifiés)', attributionRequired: false, url: mi.landing, libraryId: id },
    };
  }
  if (id.startsWith('builtin:') || id.startsWith('pack:')) {
    const src = sfxFile(id);
    file = uniquePath(path.join(dir, `${safeFileName(item.title)}${path.extname(src)}`));
    fs.copyFileSync(src, file);
  } else if (id.startsWith('music:')) {
    const src = previewSource(id)?.file;
    if (!src) throw new Error(`Missing bundled music ${id}`);
    file = path.join(dir, `${safeFileName(item.title)}.mp3`);
    if (!exists(file)) fs.copyFileSync(src, file);
  } else {
    const ext = (item.filetype || path.extname(new URL(item.url).pathname).slice(1) || 'mp3').replace(/[^a-z0-9]/gi, '').slice(0, 5) || 'mp3';
    file = uniquePath(path.join(dir, `${safeFileName(item.title)}${item.author ? ' - ' + safeFileName(item.author, 40) : ''}.${ext}`));
    await download(item.url, file, { signal, onProgress: (r, t) => onProgress?.(t ? r / t : 0) });
  }
  const sourceInfo = {
    kind: 'library', provider: item.source, title: item.title, author: item.author || null, license: item.license,
    licenseUrl: item.licenseUrl || null, attributionRequired: !!item.attributionRequired, attribution: item.attribution || null,
    url: item.landing || item.url || null, libraryId: id,
  };
  return { file, item, sourceInfo };
}

/** Attribution text for every media that requires it (to paste in the video description). */
export function creditsText(project) {
  const lines = [];
  for (const m of project.media) {
    const s = m.source || {};
    const used = project.clips.some((c) => c.mediaId === m.id);
    if (!used) continue;
    if (s.attributionRequired && s.attribution) lines.push(s.attribution);
    else if (s.kind === 'youtube' && s.url) lines.push(`"${s.title || m.name}" — ${s.author || 'YouTube'} — ${s.url}${s.license ? ` (${s.license})` : ''}`);
  }
  return [...new Set(lines)].join('\n\n');
}
